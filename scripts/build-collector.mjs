import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const adapter = '@vectorize-io/hindsight-coding-agents/dsh';
const reference = new URL(import.meta.resolve(adapter));
const expectedHash = '2664843a13fa153127bc5286915e735cfbc3c934c8307a555e8ab620512068ce';

function replaceOnce(source, before, after) {
  const position = source.indexOf(before);
  if (position === -1 || source.indexOf(before, position + before.length) !== -1) {
    throw new Error('Pinned Hindsight adapter shape changed: ' + before.slice(0, 100));
  }
  return source.slice(0, position) + after + source.slice(position + before.length);
}

export async function buildCollector() {
  const original = await readFile(reference);
  if (createHash('sha256').update(original).digest('hex') !== expectedHash) {
    throw new Error('Re-audit the exact upstream DSH adapter before updating the collector.');
  }
  let source = original.toString('utf8').replaceAll('import.meta.url', 'upstreamAdapterUrl');
  const imports = [
    '// Generated by scripts/build-collector.mjs from the pinned Hindsight DSH adapter. See HINDSIGHT-LICENSE.',
    'import { createHash as workbenchHash } from "node:crypto";',
    'import { realpathSync as workbenchRealpath, statSync as workbenchStat } from "node:fs";',
    'import { isAbsolute as workbenchAbsolute } from "node:path";',
    'const upstreamAdapterUrl = import.meta.resolve(' + JSON.stringify(adapter) + ');',
  ].join('\n');
  source = replaceOnce(source,
    '  const resolvers = {\n    harness: () => harness,',
    `  if (harness === "dsh" && (!config2.bankIdTemplate || config2.bankIdTemplate === DEFAULT_TEMPLATE)) {
    const workspace = workbenchProjectDirectory(directory);
    const project = config2.resolveWorktrees === false ? { status: "absent" } : resolveProjectRoot(workspace);
    if (project.status === "failed") throw new BankResolutionError("Git project root could not be resolved");
    const root = project.status === "resolved" ? workbenchProjectDirectory(project.root, true) : workspace;
    return "coding-agent::workspace-" + workbenchHash("sha256").update(root).digest("hex").slice(0, 32);
  }
  const resolvers = {
    harness: () => harness,`);
  source = replaceOnce(source,
    'function workspaceRoot(agent) {\n  return agent.session.header.cwd || process.cwd();\n}',
    `function workbenchProjectDirectory(directory, allowRoot = false) {
  if (typeof directory !== "string" || !workbenchAbsolute(directory)) {
    throw new BankResolutionError("No absolute session workspace path");
  }
  try {
    const canonical = workbenchRealpath.native(directory);
    if (!workbenchStat(canonical).isDirectory() || (!allowRoot && dirname4(canonical) === canonical)) {
      throw new Error("Invalid workspace directory");
    }
    return canonical;
  } catch {
    throw new BankResolutionError("Session workspace directory is unavailable");
  }
}
function workspaceRoot(agent) {
  try {
    const cwd = agent.session.header.cwd;
    workbenchProjectDirectory(cwd);
    return cwd;
  } catch {
    return undefined;
  }
}`);
  source = replaceOnce(source,
    '  return workspaceFor(workspaceRoot(agent));',
    '  const root = workspaceRoot(agent);\n  return root ? workspaceFor(root) : undefined;');
  source = replaceOnce(source,
    'const workspace = exec?.agent ? workspaceForAgent(exec.agent) : template;',
    'const workspace = exec?.agent ? workspaceForAgent(exec.agent) : undefined;');
  await writeFile('dist/collector.js', imports + '\n' + source);
}
